def L(s): return len(s)
def W(s): return sum(1.0 if ord(c) > 0x2E80 else 0.55 for c in s)

R, K = [], []
def rep(page, slot, pairs, note="", tol=1.2, wide=False):
    for o, n in pairs:
        if wide: continue
        o_a = any(ord(c) < 0x2E80 for c in o); n_a = any(ord(c) < 0x2E80 for c in n)
        if not o_a and not n_a:
            assert L(o) == L(n), f"字数不等 P{page} {slot}: [{L(o)}]{o} -> [{L(n)}]{n}"
        else:
            assert abs(W(o) - W(n)) <= tol, f"视觉宽度不等 P{page} {slot}: [{W(o):.1f}]{o} -> [{W(n):.1f}]{n}"
    R.append((page, slot, pairs, note))
def keep(page, slot, lines, reason):
    K.append((page, slot, lines, reason))

